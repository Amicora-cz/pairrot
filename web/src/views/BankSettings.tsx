import { useCallback, useEffect, useState } from 'react'
import { api, ApiError, type BankConnection, type ListResponse, type Tenant } from '../api'
import { ErrorText, Section } from '../components'
import { formatDate, useAction } from '../util'

const STUB_NOTICE = 'Test address — real bank emails are not received yet.'

/**
 * Bank connections of one tenant: the selected tenant (`/v1/tenant/bank-connections`) or a
 * direct child (`/v1/subtenants/{id}/bank-connections`). The owner is always shown, so a parent
 * administrator can tell their own account from a studio's.
 */
export function BankSettings({ basePath, owner, readOnly = false }: { basePath: string; owner: Tenant; readOnly?: boolean }) {
  const [connections, setConnections] = useState<BankConnection[]>([])
  const [includeArchived, setIncludeArchived] = useState(false)
  const { busy, error, run } = useAction()

  const reload = useCallback(async () => {
    const query = includeArchived ? '?include_archived=true' : ''
    setConnections((await api<ListResponse<BankConnection>>('GET', `${basePath}${query}`)).items)
  }, [basePath, includeArchived])

  useEffect(() => {
    void run(reload)
  }, [run, reload])

  const replace = (next: BankConnection) => setConnections((current) => current.map((c) => (c.id === next.id ? next : c)))

  return (
    <Section title={`Bank settings: ${owner.configuration.name}`}>
      <p className="muted">
        Owner: <strong>{owner.configuration.name}</strong> <code>{owner.external_id}</code>
        {owner.parent_tenant_id === null ? ' (root tenant)' : ' (subtenant)'}
      </p>
      <p className="stub-banner">
        <strong>{STUB_NOTICE}</strong> Notification addresses are generated by a local stub. Do not enter them in internet
        banking. Account details are checked for format only, not verified with the bank.
      </p>

      {!readOnly && <AddConnection basePath={basePath} onCreated={() => run(reload)} />}

      <label className="inline">
        <input type="checkbox" checked={includeArchived} onChange={(e) => setIncludeArchived(e.target.checked)} /> Show
        archived
      </label>
      <ErrorText error={error} />
      {connections.length === 0 && !busy && <p className="muted">No bank connections yet.</p>}
      {connections.map((c) => (
        <ConnectionCard key={c.id} basePath={basePath} connection={c} readOnly={readOnly} onChanged={replace} onArchived={() => run(reload)} />
      ))}
    </Section>
  )
}

function AddConnection({ basePath, onCreated }: { basePath: string; onCreated: () => Promise<void> }) {
  const [form, setForm] = useState({ account_number: '', iban: '', label: '' })
  const { busy, error, run, setError } = useAction()
  const fieldError = (field: string) =>
    error instanceof ApiError && error.field === field ? <span className="field-error">{error.message}</span> : null
  const generalError = error instanceof ApiError && error.field ? null : error

  return (
    <form
      onSubmit={(e) => {
        e.preventDefault()
        // The SPA only trims; validation and normalization happen in the API.
        const body: Record<string, string> = {}
        if (form.account_number.trim()) body.account_number = form.account_number.trim()
        if (form.iban.trim()) body.iban = form.iban.trim()
        if (form.label.trim()) body.label = form.label.trim()
        void run(async () => {
          await api<BankConnection>('POST', basePath, body)
          setForm({ account_number: '', iban: '', label: '' })
          await onCreated()
        })
      }}
    >
      <p className="muted">Enter a Czech account number, a Czech IBAN, or both. Only CZK is supported.</p>
      <label>
        Account number
        <input
          placeholder="19-2000145399/0800"
          value={form.account_number}
          onChange={(e) => {
            setError(null)
            setForm({ ...form, account_number: e.target.value })
          }}
        />
        {fieldError('account_number')}
      </label>
      <label>
        IBAN
        <input
          placeholder="CZ65 0800 0000 1920 0014 5399"
          value={form.iban}
          onChange={(e) => {
            setError(null)
            setForm({ ...form, iban: e.target.value })
          }}
        />
        {fieldError('iban')}
      </label>
      <label>
        Label (optional)
        <input placeholder="Main account" value={form.label} onChange={(e) => setForm({ ...form, label: e.target.value })} />
        {fieldError('label')}
      </label>
      {fieldError('currency')}
      <ErrorText error={generalError} />
      <button type="submit" disabled={busy}>
        Add bank account
      </button>
    </form>
  )
}

function ConnectionCard({
  basePath,
  connection: c,
  readOnly,
  onChanged,
  onArchived,
}: {
  basePath: string
  connection: BankConnection
  readOnly: boolean
  onChanged: (c: BankConnection) => void
  onArchived: () => Promise<void>
}) {
  const [label, setLabel] = useState(c.label ?? '')
  const [copied, setCopied] = useState(false)
  const { busy, error, run } = useAction()
  const path = `${basePath}/${c.id}`
  const archived = c.status === 'archived'
  const canChange = !readOnly && !archived

  return (
    <div className={`connection ${archived ? 'archived' : ''}`}>
      <div className="row">
        <strong>{c.label ?? 'Unlabelled account'}</strong>
        <span className={`badge badge-${c.status}`}>{c.status}</span>
      </div>
      <dl>
        <dt>Account number</dt>
        <dd>
          <code>{c.account_number}</code>
        </dd>
        <dt>IBAN</dt>
        <dd>
          <code>{c.iban}</code>
        </dd>
        <dt>Currency</dt>
        <dd>{c.currency}</dd>
        <dt>Created</dt>
        <dd>{formatDate(c.created_at)}</dd>
        {archived && (
          <>
            <dt>Archived</dt>
            <dd>{formatDate(c.archived_at)}</dd>
          </>
        )}
        <dt>Notification address</dt>
        <dd>
          {c.inbound_address ? (
            <>
              <code>{c.inbound_address}</code>{' '}
              <button
                className="secondary"
                onClick={async () => {
                  await navigator.clipboard.writeText(c.inbound_address!)
                  setCopied(true)
                }}
              >
                {copied ? 'Copied' : 'Copy'}
              </button>
              <br />
              <span className="muted">
                {STUB_NOTICE} Provider: {c.email_provider}, assigned {formatDate(c.address_created_at)}
                {archived && '. Kept for history; the connection is archived.'}
              </span>
            </>
          ) : (
            <span className="muted">Not created{archived && ' (archived connections cannot get an address)'}</span>
          )}
        </dd>
      </dl>

      {canChange && (
        <div className="row">
          {!c.inbound_address && (
            <button disabled={busy} onClick={() => void run(async () => onChanged(await api<BankConnection>('POST', `${path}/inbound-address`)))}>
              Create notification address
            </button>
          )}
          <form
            className="row"
            onSubmit={(e) => {
              e.preventDefault()
              void run(async () => onChanged(await api<BankConnection>('PATCH', path, { label: label.trim() === '' ? null : label })))
            }}
          >
            <input placeholder="Label" value={label} onChange={(e) => setLabel(e.target.value)} />
            <button type="submit" className="secondary" disabled={busy || label === (c.label ?? '')}>
              Save label
            </button>
          </form>
          <button
            className="danger"
            disabled={busy}
            onClick={() => {
              if (!confirm(`Archive ${c.account_number}? Its details and address are kept, but the account cannot be added again.`)) return
              void run(async () => {
                await api('DELETE', path)
                await onArchived()
              })
            }}
          >
            Archive
          </button>
        </div>
      )}
      <ErrorText error={error} />
    </div>
  )
}
